def classify(name):
    if pd.isna(name):
        return (pd.NA, "non_drug", "no name")
    n = str(name).lower().strip()
    if n in HEPATOTOXIC:
        return (1, "expert_curation", HEPATOTOXIC[n])
    if n in SAFE_DRUGS:
        return (0, "expert_curation", SAFE_DRUGS[n])
    if n in NON_DRUG:
        return (pd.NA, "non_drug", NON_DRUG[n])
    return None  # need WebSearch

